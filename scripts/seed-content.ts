/* Syncs the in-code curriculum into the content tables (worlds, lessons, exercises, achievements).
   Usage:
     npm run db:seed              # upserts via Supabase (needs NEXT_PUBLIC_SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY)
     npm run db:seed -- --sql     # writes supabase/seed.sql instead (paste into the SQL editor)
*/
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { WORLDS } from "../src/lib/content";
import { publicAchievements } from "../src/lib/engine/achievements";

const worlds = WORLDS.map((w) => ({ id: w.id, position: w.index, title: w.title, tagline: w.tagline, built: w.lessons.length > 0 }));
const lessons = WORLDS.flatMap((w) => [
  ...w.lessons.map((l, i) => ({ id: l.id, world_id: w.id, position: i + 1, title: l.title, summary: l.summary, is_boss: false })),
  ...(w.lessons.length ? [{ id: `${w.id}-boss`, world_id: w.id, position: 99, title: `Bossutmaning: ${w.title}`, summary: "Blandat slutprov för hela världen", is_boss: true }] : []),
]);
const exercises = WORLDS.flatMap((w) => w.lessons.flatMap((l) => (["knowledge", "method", "representation"] as const).flatMap((s) => l[s].map((t) => ({ id: `${l.id}:${t.id}`, lesson_id: l.id, section: s, template_id: t.id, skill: t.skill })))));
const achievements = publicAchievements;

const q = (v: unknown) => (typeof v === "boolean" || typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const insert = (table: string, rows: Record<string, unknown>[], conflict: string) => {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const set = cols.filter((c) => c !== conflict).map((c) => `${c}=excluded.${c}`).join(", ");
  return `insert into public.${table} (${cols.join(", ")}) values\n${rows.map((r) => `  (${cols.map((c) => q(r[c])).join(", ")})`).join(",\n")}\non conflict (${conflict}) do update set ${set};\n`;
};

async function main() {
  if (process.argv.includes("--sql")) {
    writeFileSync("supabase/seed.sql", ["-- generated by scripts/seed-content.ts", insert("worlds", worlds, "id"), insert("lessons", lessons, "id"), insert("exercises", exercises, "id"), insert("achievements", achievements, "id")].join("\n"));
    console.log(`wrote supabase/seed.sql (${worlds.length} worlds, ${lessons.length} lessons, ${exercises.length} exercise templates, ${achievements.length} achievements)`);
    return;
  }
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL, key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !key) throw new Error("Sätt NEXT_PUBLIC_SUPABASE_URL och SUPABASE_SERVICE_ROLE_KEY (eller kör med --sql).");
  const db = createClient(url, key, { auth: { persistSession: false } });
  for (const [table, rows] of [["worlds", worlds], ["lessons", lessons], ["exercises", exercises], ["achievements", achievements]] as const) {
    const { error } = await db.from(table).upsert(rows as never, { onConflict: "id" });
    if (error) throw new Error(`${table}: ${error.message}`);
    console.log(`upserted ${rows.length} ${table}`);
  }
}
main().catch((e) => { console.error(e.message); process.exit(1); });
